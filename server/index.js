const CATEGORIES = new Set(['Hypercar', 'Grand Tourer', 'Luxury SUV', 'Concept']);
const CAR_STATUSES = new Set(['Floor Display', 'Pre-Order', 'Reserved', 'Service']);

function cleanString(value, field, max, required = true) {
  if (typeof value !== 'string') throw Object.assign(new Error(`${field} must be text.`), { status: 400 });
  const result = value.trim();
  if (required && !result) throw Object.assign(new Error(`${field} is required.`), { status: 400 });
  if (result.length > max || /[\u0000-\u0008\u000B\u000C\u000E-\u001F]/.test(result)) {
    throw Object.assign(new Error(`${field} is invalid or too long.`), { status: 400 });
  }
  return result;
}

function validateCar(input, existing = {}) {
  const name = cleanString(input.name ?? existing.name, 'Vehicle name', 80);
  const series = cleanString(input.series ?? existing.series ?? '', 'Series', 80, false);
  const category = input.category ?? existing.category ?? 'Hypercar';
  if (!CATEGORIES.has(category)) throw Object.assign(new Error('Choose a valid vehicle category.'), { status: 400 });
  const year = Number(input.year ?? existing.year ?? new Date().getFullYear());
  const price = Number(input.price ?? existing.price);
  const hp = Number(input.hp ?? existing.hp);
  const topSpeed = Number(input.topSpeed ?? existing.topSpeed ?? 0);
  const bayRaw = input.bay ?? existing.bay;
  const bay = bayRaw === '' || bayRaw === null || bayRaw === undefined ? null : Number(bayRaw);
  const colorRaw = input.colorHex ?? existing.colorHex ?? 0xd8dde4;
  const colorHex = typeof colorRaw === 'string' && /^#[0-9a-fA-F]{6}$/.test(colorRaw)
    ? Number.parseInt(colorRaw.slice(1), 16)
    : Number(colorRaw);
  const finish = input.finish ?? existing.finish ?? 'metallic';
  const status = input.status ?? existing.status ?? 'Floor Display';
  const colorName = cleanString(input.colorName ?? existing.colorName ?? 'Custom Paint', 'Paint name', 60);
  const numberCheck = (value, field, min, max) => {
    if (!Number.isInteger(value) || value < min || value > max) {
      throw Object.assign(new Error(`${field} must be between ${min} and ${max}.`), { status: 400 });
    }
  };
  numberCheck(year, 'Year', 1950, 2100);
  numberCheck(price, 'Price', 0, 100_000_000);
  numberCheck(hp, 'Horsepower', 0, 10_000);
  numberCheck(topSpeed, 'Top speed', 0, 500);
  if (bay !== null) numberCheck(bay, 'Bay', 1, SHOWROOM_BAYS.length);
  if (!Number.isInteger(colorHex) || colorHex < 0 || colorHex > 0xffffff) {
    throw Object.assign(new Error('Choose a valid paint color.'), { status: 400 });
  }
  if (!['metallic', 'gloss', 'matte', 'pearlescent'].includes(finish)) {
    throw Object.assign(new Error('Choose a valid paint finish.'), { status: 400 });
  }
  if (!CAR_STATUSES.has(status)) throw Object.assign(new Error('Choose a valid inventory status.'), { status: 400 });
  return {
    ...existing,
    id: existing.id || `car-${randomUUID()}`,
    name,
    series,
    year,
    category,
    price,
    hp,
    topSpeed,
    colorName,
    colorHex,
    finish,
    bay,
    status,
    inStock: Number.isInteger(existing.inStock) ? existing.inStock : 1,
    views: Number.isInteger(existing.views) ? existing.views : 0,
  };
}

function assignVacantBay(requestedBay, currentId = null) {
  const used = new Set(db.prepare('SELECT bay FROM cars WHERE (? IS NULL OR id != ?)').all(currentId, currentId).map(row => row.bay));
  if (requestedBay !== null && used.has(requestedBay)) {
    throw Object.assign(new Error('That bay is already occupied. Choose an open bay.'), { status: 409 });
  }
  const bay = requestedBay ?? SHOWROOM_BAYS.find(item => !used.has(item.bay))?.bay;
  if (!bay) throw Object.assign(new Error('All showroom bays are occupied.'), { status: 409 });
  return bay;
}

function validateInquiry(input) {
  const name = cleanString(input.name, 'Name', 60);
  if (!/^[\p{L}\p{M}\s'-]{2,60}$/u.test(name)) throw Object.assign(new Error('Enter a valid name.'), { status: 400 });
  const rawPhone = cleanString(input.phone, 'Phone', 20).replace(/[\s\-()]/g, '');
  const phone = rawPhone.startsWith('+91') ? rawPhone.slice(3) : rawPhone.startsWith('91') && rawPhone.length === 12 ? rawPhone.slice(2) : rawPhone;
  if (!/^[6-9]\d{9}$/.test(phone)) throw Object.assign(new Error('Enter a valid 10-digit mobile number.'), { status: 400 });
  const email = cleanString(input.email, 'Email', 254);
  if (!/^[^\s@<>]+@[^\s@<>]+\.[^\s@<>]+$/.test(email)) throw Object.assign(new Error('Enter a valid email address.'), { status: 400 });
  const preferredDate = cleanString(input.date, 'Preferred date', 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(preferredDate)) throw Object.assign(new Error('Choose a valid preferred date.'), { status: 400 });
  const selected = new Date(`${preferredDate}T00:00:00.000Z`);
  const now = new Date();
  const today = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
  const max = new Date(today.getTime() + 60 * 24 * 60 * 60 * 1000);
  if (Number.isNaN(selected.getTime()) || selected < today || selected > max || selected.toISOString().slice(0, 10) !== preferredDate) {
    throw Object.assign(new Error('Choose a date within the next 60 days.'), { status: 400 });
  }
  const carId = cleanString(input.carId, 'Vehicle', 80);
  const message = cleanString(input.message || '', 'Message', 500, false);
  const carRow = db.prepare('SELECT data FROM cars WHERE id = ?').get(carId);
  if (!carRow) throw Object.assign(new Error('Choose a vehicle from the current inventory.'), { status: 400 });
  return { name, phone, email, preferredDate, carId, carName: JSON.parse(carRow.data).name, message };
}

function csvCell(value) {
  let text = String(value ?? '');
  if (/^[\s]*[=+\-@]/.test(text)) text = `'${text}`;
  return `"${text.replaceAll('"', '""')}"`;
}

async function serveStatic(req, res, pathname) {
  if (!['GET', 'HEAD'].includes(req.method)) return fail(res, 405, 'Method not allowed.');
  try {
    const decoded = decodeURIComponent(pathname);
    const relative = decoded === '/' ? 'index.html' : decoded.replace(/^\/+/, '');
    if (relative.split(/[\\/]/).includes('..')) return fail(res, 400, 'Invalid path.');
    const filePath = resolve(DIST, relative);
    if (filePath !== DIST && !filePath.startsWith(`${DIST}${sep}`)) return fail(res, 400, 'Invalid path.');
    const stat = await access(filePath).then(() => statSync(filePath));
    if (!stat.isFile()) return fail(res, 404, 'Not found.');
    const mime = {
      '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
      '.json': 'application/json; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg',
      '.jpeg': 'image/jpeg', '.hdr': 'application/octet-stream', '.glb': 'model/gltf-binary', '.wasm': 'application/wasm',
    }[extname(filePath).toLowerCase()] || 'application/octet-stream';
    res.writeHead(200, { 'Content-Type': mime, 'Content-Length': stat.size, 'Cache-Control': extname(filePath) === '.html' ? 'no-store' : 'public, max-age=3600' });
    if (req.method === 'HEAD') return res.end();
    res.end(await readFile(filePath));
  } catch {
    fail(res, 404, 'Not found.');
  }
}

async function handle(req, res) {
  securityHeaders(res);
  const requestUrl = new URL(req.url || '/', publicOrigin || `http://${req.headers.host || 'localhost'}`);
  const path = requestUrl.pathname;
  try {
    if (path === '/api/health' && req.method === 'GET') return json(res, 200, { status: 'ok' });

    if (path === '/api/auth/session' && req.method === 'GET') {
      const rate = limited(`session:${clientAddress(req)}`, 120, 15 * 60 * 1000);
      if (!rate.allowed) return fail(res, 429, 'Too many session requests. Try again later.', { 'Retry-After': String(rate.retryAfter) });
      const existing = getSession(req);
      if (existing) return json(res, 200, {
        authenticated: existing.session.authenticated,
        csrfToken: existing.session.csrfToken,
        expiresAt: new Date(existing.session.expiresAt).toISOString(),
      });
      const session = createSession(res, false);
      return json(res, 200, session);
    }

    if (path === '/api/auth/login' && req.method === 'POST') {
      if (!allowedOrigin(req)) return fail(res, 403, 'Request origin is not allowed.');
      const rate = limited(`login:${clientAddress(req)}`, 5, 15 * 60 * 1000);
      if (!rate.allowed) return fail(res, 429, 'Too many sign-in attempts. Try again later.', { 'Retry-After': String(rate.retryAfter) });
      const entry = checkMutation(req, res, false);
      if (!entry) return;
      let body;
      try { body = await readJson(req, 4 * 1024); } catch (error) { return fail(res, error.status || 400, error.message); }
      const submitted = typeof body.password === 'string' ? body.password : '';
      const candidate = scryptSync(submitted, passwordSalt, 64);
      const passwordMatches = submitted.length <= 1024 && timingSafeEqual(candidate, expectedPasswordHash);
      const totpStep = matchingTotpStep(typeof body.code === 'string' ? body.code : '');
      if (!passwordMatches || totpStep === null) return fail(res, 401, 'Password or verification code is incorrect or expired.');
      const acceptedStep = db.prepare("UPDATE auth_state SET value = ? WHERE key = 'last_totp_step' AND value < ?").run(totpStep, totpStep).changes;
      if (!acceptedStep) return fail(res, 401, 'Password or verification code is incorrect or expired.');
      sessionStore.delete(entry.id);
      rateLimits.delete(`login:${clientAddress(req)}`);
      return json(res, 200, createSession(res, true));
    }

    if (path === '/api/auth/logout' && req.method === 'POST') {
      const entry = checkMutation(req, res, true);
      if (!entry) return;
      sessionStore.delete(entry.id);
      clearSessionCookie(res);
      return json(res, 200, { ok: true });
    }

    if (path === '/api/inventory' && req.method === 'GET') {
      return json(res, 200, { cars: listCars() });
    }

    if (path === '/api/inquiries' && req.method === 'POST') {
      if (!checkMutation(req, res, false)) return;
      const rate = limited(`inquiry:${clientAddress(req)}`, 8, 60 * 60 * 1000);
      if (!rate.allowed) return fail(res, 429, 'Too many requests. Please try again later.', { 'Retry-After': String(rate.retryAfter) });
      let body;
      try { body = await readJson(req); } catch (error) { return fail(res, error.status || 400, error.message); }
      const inquiry = validateInquiry(body);
      const record = { id: `inq-${randomUUID()}`, ...inquiry, status: 'New', createdAt: new Date().toISOString() };
      db.prepare('INSERT INTO inquiries (id, data, status, created_at) VALUES (?, ?, ?, ?)').run(
        record.id, encryptRecord(record), record.status, record.createdAt,
      );
      return json(res, 201, { inquiry: record });
    }

    if (path.startsWith('/api/admin/')) {
      if (!requireAdmin(req, res)) return;
      if (['POST', 'PATCH', 'PUT', 'DELETE'].includes(req.method) && !checkMutation(req, res, true)) return;
    }

    if (path === '/api/admin/dashboard' && req.method === 'GET') {
      const cars = listCars();
      const inquiries = listInquiries(250);
      const openInquiries = db.prepare("SELECT COUNT(*) AS count FROM inquiries WHERE status IN ('New', 'Contacted', 'Qualified')").get().count;
      const newInquiries = db.prepare("SELECT COUNT(*) AS count FROM inquiries WHERE status = 'New'").get().count;
      const fleetValue = cars.reduce((sum, car) => sum + car.price, 0);
      return json(res, 200, {
        cars,
        inquiries,
        stats: { totalCars: cars.length, fleetValue, occupiedBays: new Set(cars.map(car => car.bay)).size, totalBays: SHOWROOM_BAYS.length, openInquiries, newInquiries, totalInquiries: db.prepare('SELECT COUNT(*) AS count FROM inquiries').get().count },
      });
    }

    if (path === '/api/admin/cars' && req.method === 'POST') {
      const body = await readJson(req);
      const car = validateCar(body);
      car.bay = assignVacantBay(car.bay);
      db.prepare('INSERT INTO cars (id, bay, data) VALUES (?, ?, ?)').run(car.id, car.bay, JSON.stringify(car));
      return json(res, 201, { car });
    }

    const carRoute = path.match(/^\/api\/admin\/cars\/([^/]+)$/);
    if (carRoute && req.method === 'PATCH') {
      const id = decodeURIComponent(carRoute[1]);
      const row = db.prepare('SELECT data FROM cars WHERE id = ?').get(id);
      if (!row) return fail(res, 404, 'Vehicle not found.');
      const body = await readJson(req);
      const car = validateCar(body, JSON.parse(row.data));
      car.bay = assignVacantBay(car.bay, id);
      db.prepare('UPDATE cars SET bay = ?, data = ? WHERE id = ?').run(car.bay, JSON.stringify(car), id);
      return json(res, 200, { car });
    }
    if (carRoute && req.method === 'DELETE') {
      const id = decodeURIComponent(carRoute[1]);
      if (!db.prepare('DELETE FROM cars WHERE id = ?').run(id).changes) return fail(res, 404, 'Vehicle not found.');
      return json(res, 200, { ok: true });
    }

    if (path === '/api/admin/inquiries/export.csv' && req.method === 'GET') {
      const rows = listInquiries(10000);
      const headers = ['Created at', 'Name', 'Email', 'Phone', 'Vehicle', 'Preferred date', 'Message', 'Status'];
      const lines = [headers.map(csvCell).join(',')];
      for (const item of rows) lines.push([item.createdAt, item.name, item.email, item.phone, item.carName, item.preferredDate, item.message, item.status].map(csvCell).join(','));
      res.writeHead(200, { 'Content-Type': 'text/csv; charset=utf-8', 'Content-Disposition': 'attachment; filename="showroom-inquiries.csv"', 'Cache-Control': 'no-store' });
      return res.end(`\uFEFF${lines.join('\r\n')}`);
    }

    const inquiryRoute = path.match(/^\/api\/admin\/inquiries\/([^/]+)$/);
    if (inquiryRoute && req.method === 'PATCH') {
      const id = decodeURIComponent(inquiryRoute[1]);
      const body = await readJson(req, 4 * 1024);
      const status = body.status;
      if (!['New', 'Contacted', 'Qualified', 'Closed', 'Spam'].includes(status)) return fail(res, 400, 'Choose a valid inquiry status.');
      const result = db.prepare('UPDATE inquiries SET status = ? WHERE id = ?').run(status, id);
      if (!result.changes) return fail(res, 404, 'Inquiry not found.');
      return json(res, 200, { ok: true });
    }
    if (inquiryRoute && req.method === 'DELETE') {
      const result = db.prepare('DELETE FROM inquiries WHERE id = ?').run(decodeURIComponent(inquiryRoute[1]));
      if (!result.changes) return fail(res, 404, 'Inquiry not found.');
      return json(res, 200, { ok: true });
    }

    if (path.startsWith('/api/')) return fail(res, 404, 'API endpoint not found.');
    if (isProduction) return serveStatic(req, res, path);
    return fail(res, 404, 'API server is ready. Use the Vite development server for app pages.');
  } catch (error) {
    if (error.code === 'SQLITE_CONSTRAINT_UNIQUE') return fail(res, 409, 'That showroom bay is already occupied.');
    console.error('Request failed:', error.message);
    return fail(res, error.status || 500, error.status ? error.message : 'The request could not be completed.');
  }
}

const server = createServer((req, res) => {
  handle(req, res).catch(error => {
    console.error('Unhandled request error:', error.message);
    if (!res.headersSent) fail(res, 500, 'The request could not be completed.');
    else res.destroy();
  });
});

const cleanup = setInterval(() => {
  const now = Date.now();
  for (const [id, session] of sessionStore) if (session.expiresAt <= now) sessionStore.delete(id);
  for (const [key, rate] of rateLimits) if (rate.resetAt <= now) rateLimits.delete(key);
}, 60_000);
cleanup.unref();

server.listen(port, host, () => {
  console.log(`Showroom service listening on http://${host}:${port}`);
  if (isProduction) console.log(`Serving production app for ${publicOrigin}`);
});

function shutdown() {
  clearInterval(cleanup);
  server.close(() => {
    db.close();
    process.exit(0);
  });
  setTimeout(() => process.exit(1), 5_000).unref();
}
process.on('SIGINT', shutdown);
process.on('SIGTERM', shutdown);
